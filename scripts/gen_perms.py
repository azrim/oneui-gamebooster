#!/usr/bin/env python3
"""Generate the module's additive permission XMLs from the bundled APKs.

For every package we emit the union of the permissions its APKs request that are
'signature|privileged' (per data/privileged-permissions.txt). This keeps
ro.control_privapp_permissions=enforce from tripping on our apps, and grants the
Game Launcher its platform signature permissions.

The files are ADDITIVE: their names are unique to this module, so the platform
merges them with whatever allowlist the ROM already ships instead of replacing it.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from axml import apk_info  # noqa: E402

PRIVAPP_FILE = 'privapp-permissions-samsung-gamebooster.xml'
SIGPERM_FILE = 'signature-permissions-samsung-gamebooster.xml'

HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by scripts/gen_perms.py - additive, merged with any ROM-provided allowlist -->\n'
          '<permissions>\n')


def load_priv(path):
    s = set()
    for line in open(path, encoding='utf-8'):
        line = line.strip()
        if line and not line.startswith('#'):
            s.add(line)
    return s


def collect(apks, priv):
    """{package: sorted([privileged perms requested])} plus a version summary."""
    pkgs = {}
    summary = []
    for apk in apks:
        info = apk_info(apk)
        pkg = info['package']
        if not pkg:
            raise SystemExit(f"no package in {apk}")
        rp = sorted(p for p in info['permissions'] if p in priv)
        pkgs.setdefault(pkg, set()).update(rp)
        summary.append((os.path.basename(apk), pkg, info['versionName'], info['minSdk'], len(rp)))
    return {k: sorted(v) for k, v in pkgs.items()}, summary


def emit(tag, pkgs):
    out = [HEADER.rstrip('\n')]
    for pkg, perms in pkgs.items():
        out.append(f'    <{tag} package="{pkg}">')
        for p in perms:
            out.append(f'        <permission name="{p}"/>')
        out.append(f'    </{tag}>')
    out.append('</permissions>')
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--priv-list', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--privapp', nargs='+', default=[], metavar='APK')
    ap.add_argument('--signature', nargs='+', default=[], metavar='APK')
    a = ap.parse_args()

    priv = load_priv(a.priv_list)
    os.makedirs(a.out, exist_ok=True)

    if a.privapp:
        pkgs, summary = collect(a.privapp, priv)
        with open(os.path.join(a.out, PRIVAPP_FILE), 'w') as f:
            f.write(emit('privapp-permissions', pkgs))
        print(f"wrote {PRIVAPP_FILE}")
        for name, pkg, ver, minsdk, n in summary:
            print(f"    {name}: {pkg} {ver} (minSdk {minsdk}) -> {n} privileged perms")

    if a.signature:
        pkgs, summary = collect(a.signature, priv)
        with open(os.path.join(a.out, SIGPERM_FILE), 'w') as f:
            f.write(emit('signature-permissions', pkgs))
        print(f"wrote {SIGPERM_FILE}")
        for name, pkg, ver, minsdk, n in summary:
            print(f"    {name}: {pkg} {ver} (minSdk {minsdk}) -> {n} privileged perms")


if __name__ == '__main__':
    main()
